package ifelse;

public class PrintXY {
    public static void main(String[] args) {
        int x = 1500;
        int y = 300;

        if (x < 2000 || x > 3000) {
            System.out.println("x = " + x);
        }
        if (y > 100 && y < 500) {
            System.out.println("y = " + y);
        }
    }
}
